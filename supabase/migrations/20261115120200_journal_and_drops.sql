-- Journal (editorial / lookbook posts) and Drops (limited collections and
-- collaborations). Same translation pattern as products: English lives in the
-- main table, el/da/de in *_translations, and missing fields fall back to English.

-- ---------------------------------------------------------------- Journal --

create table if not exists public.journal_posts (
  id           bigint      generated by default as identity primary key,
  slug         text        not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title        text        not null,
  excerpt      text,
  -- Plain text. Blank lines separate paragraphs; a line starting with "## " is
  -- a heading. Keeps the editor simple (Supabase table editor) and safe (no HTML).
  body         text        not null default '',
  cover_image  text,
  author       text,
  -- Products shown under the post ("Shop the look").
  product_ids  bigint[]    not null default '{}',
  published_at timestamptz,             -- null = draft, future = scheduled
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists journal_posts_published_idx
  on public.journal_posts (published_at desc);

create table if not exists public.journal_post_translations (
  post_id    bigint not null references public.journal_posts(id) on delete cascade,
  locale     text   not null check (locale in ('el', 'da', 'de')),
  title      text,
  excerpt    text,
  body       text,
  updated_at timestamptz not null default now(),
  primary key (post_id, locale)
);

alter table public.journal_posts             enable row level security;
alter table public.journal_post_translations enable row level security;

drop policy if exists "Public read published" on public.journal_posts;
create policy "Public read published" on public.journal_posts
  for select using (published_at is not null and published_at <= now());

drop policy if exists "Public read" on public.journal_post_translations;
create policy "Public read" on public.journal_post_translations
  for select using (true);

-- ------------------------------------------------------------------ Drops --

create table if not exists public.drops (
  id                bigint      generated by default as identity primary key,
  slug              text        not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title             text        not null,
  tagline           text,
  description       text,
  hero_image        text,
  -- Collaborations: who we made it with. Leave empty for an in-house drop.
  collaborator_name text,
  collaborator_bio  text,
  collaborator_url  text,
  collaborator_image text,
  starts_at         timestamptz not null,  -- products are shown from this moment
  ends_at           timestamptz,
  is_published      boolean     not null default false,  -- false = hidden
  launch_notified_at timestamptz,          -- set when early-access emails went out
  created_at        timestamptz not null default now()
);

create index if not exists drops_starts_at_idx on public.drops (starts_at desc);

create table if not exists public.drop_translations (
  drop_id          bigint not null references public.drops(id) on delete cascade,
  locale           text   not null check (locale in ('el', 'da', 'de')),
  title            text,
  tagline          text,
  description      text,
  collaborator_bio text,
  updated_at       timestamptz not null default now(),
  primary key (drop_id, locale)
);

create table if not exists public.drop_products (
  drop_id    bigint not null references public.drops(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  position   int    not null default 0,
  primary key (drop_id, product_id)
);

-- "Notify me when it drops." Written by the server only.
create table if not exists public.drop_signups (
  id          uuid        primary key default gen_random_uuid(),
  drop_id     bigint      not null references public.drops(id) on delete cascade,
  email       text        not null check (email = lower(email)),
  locale      text        not null default 'en',
  created_at  timestamptz not null default now(),
  notified_at timestamptz,
  unique (drop_id, email)
);

alter table public.drops             enable row level security;
alter table public.drop_translations enable row level security;
alter table public.drop_products     enable row level security;
alter table public.drop_signups      enable row level security;

-- Published drops are public before launch too (teaser + countdown); the app
-- only lists their products once starts_at has passed.
drop policy if exists "Public read published" on public.drops;
create policy "Public read published" on public.drops
  for select using (is_published);

drop policy if exists "Public read" on public.drop_translations;
create policy "Public read" on public.drop_translations for select using (true);

drop policy if exists "Public read" on public.drop_products;
create policy "Public read" on public.drop_products for select using (true);
